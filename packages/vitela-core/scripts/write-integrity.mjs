// Writes src/generated/integrity.{js,d.ts}: the sha256 of each asset the
// worker may fetch from a custom assetBaseUrl, computed from the exact files
// copy-assets.mjs ships in dist/. The worker refuses CDN copies that differ.
// Runs after build:wasm and before every build, so it never goes stale.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const generated = (path) => fileURLToPath(new URL(`../src/generated/${path}`, import.meta.url));

// File name (as served under assetBaseUrl) -> path under src/generated/.
const ASSETS = {
  'pdf_wasm_bg.wasm': 'engine/pdf_wasm_bg.wasm',
  'pdfium.js': 'pdfium/pdfium.js',
  'pdfium.wasm': 'pdfium/pdfium.wasm',
};

const digests = {};
for (const [name, path] of Object.entries(ASSETS)) {
  if (!existsSync(generated(path))) {
    console.error(`error: missing src/generated/${path}; run \`npm run build:wasm\` first`);
    process.exit(1);
  }
  digests[name] = createHash('sha256').update(readFileSync(generated(path))).digest('hex');
}

const header = '// Generated by scripts/write-integrity.mjs. Do not edit.\n';
writeFileSync(
  generated('integrity.js'),
  `${header}export const ASSET_SHA256 = Object.freeze(${JSON.stringify(digests, null, 2)});\n`,
);
writeFileSync(
  generated('integrity.d.ts'),
  `${header}/** Lower-case hex sha256 of each engine asset, by file name. */\nexport declare const ASSET_SHA256: Readonly<Record<string, string>>;\n`,
);
