#!/usr/bin/env python3
"""Generates afm_widths.rs: the 0x80..=0xFF WinAnsiEncoding widths of the
Latin standard-14 faces, from the Adobe Core14 AFM metrics reportlab embeds.

    python core/pdf-edit/src/encoding/gen_afm_widths.py

Only the high half is generated: 0x20..=0x7E lives in tables.rs, and the
Oblique faces share their upright face's metrics (checked below). Courier
is fixed pitch, 600 everywhere, so it needs no table.
"""

from pathlib import Path

from reportlab.pdfbase import _fontdata

# Codes WinAnsiEncoding leaves undefined; reportlab paints them as bullets.
UNDEFINED = {0x81, 0x8D, 0x8F, 0x90, 0x9D}
FACES = {
    "HELVETICA": "Helvetica",
    "HELVETICA_BOLD": "Helvetica-Bold",
    "TIMES_ROMAN": "Times-Roman",
    "TIMES_BOLD": "Times-Bold",
    "TIMES_ITALIC": "Times-Italic",
    "TIMES_BOLDITALIC": "Times-BoldItalic",
}
SHARED = {"Helvetica-Oblique": "Helvetica", "Helvetica-BoldOblique": "Helvetica-Bold"}


def high_widths(face: str) -> list[int]:
    glyphs = _fontdata.encodings["WinAnsiEncoding"]
    metrics = _fontdata.widthsByFontGlyph[face]
    return [0 if code in UNDEFINED else metrics[glyphs[code]] for code in range(0x80, 0x100)]


def main() -> None:
    for oblique, upright in SHARED.items():
        assert high_widths(oblique) == high_widths(upright), oblique
    out = [
        "//! Generated by gen_afm_widths.py from the Adobe Core14 AFM metrics.",
        "//! Do not edit by hand: rerun the script.",
        "//!",
        "//! WinAnsiEncoding widths for 0x80..=0xFF, in code order, 1/1000 em.",
        "//! Codes the encoding leaves undefined are 0.",
    ]
    for const, face in FACES.items():
        widths = high_widths(face)
        out.append("")
        out.append(f"/// `{face}` 0x80..=0xFF.")
        out.append(f"pub const {const}_HIGH: [u16; 128] = [")
        for row in range(0, 128, 16):
            cells = ", ".join(str(w) for w in widths[row : row + 16])
            out.append(f"    {cells}, // 0x{0x80 + row:02X}")
        out.append("];")
    path = Path(__file__).with_name("afm_widths.rs")
    path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
