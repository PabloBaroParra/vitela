//! T-191's measurement, kept as a test so the numbers in the ficha can be
//! re-derived rather than believed.
//!
//! `docs/batch-compress.md` fact 4 is written as a question, not a claim:
//! *today's save path rewrites a document that arrived with object streams as
//! loose objects plus a classic cross-reference table, and that may inflate
//! it — measure, do not assume.* This file is the measurement. It walks the
//! repository's real PDF corpus and, for each file, reports three sizes:
//!
//! 1. what the user handed us,
//! 2. what today's `pdf-save` full rewrite produces (`load_mem` + `save_to`,
//!    `strategy.rs:451`),
//! 3. what [`pdf_compress::compress`] produces.
//!
//! Run the table yourself with:
//!
//! ```text
//! cargo test -p pdf-compress --test corpus -- --nocapture measure
//! ```
//!
//! The rest of the file is the part that runs in CI: a guardian that no real
//! document in the corpus grows under any preset, that every page survives,
//! and that the protected files come back untouched. T-197 widens this corpus
//! (a scan, a pure-vector file, one with real transparency); T-191 measures
//! what the repository already has.

use std::path::{Path, PathBuf};

use pdf_compress::{compress, CompressPreset, Outcome, Refusal};

/// One corpus entry: where it lives, and what it is there to represent.
struct Fixture {
    path: &'static str,
    what: &'static str,
    /// Generated by `gen-fixtures` rather than committed, so a clean checkout
    /// that has not run the generator simply has fewer rows.
    generated: bool,
    /// Encrypted or signed: this crate hands it back untouched, so it is a
    /// row about a refusal rather than about a saving.
    protected: bool,
}

